"""Tax report renderers: PDF, generic CSV, and Form 8949 CSV.

All three take the same TaxReport object produced by calculator.py and
emit bytes ready to be streamed back by the API layer.

PDF design notes
----------------
The PDF matches the house style from /root/telegram-claude/md_to_pdf.py
— teal accents (#00a7d4), dark code blocks, page numbers — but the
content is hand-rolled HTML so we get tight control over the tables
(Form 8949 format is picky about column order and widths).

Layout per page:
  • Cover block: jurisdiction, year, method, generated timestamp
  • Summary table: short vs long term, net gain, taxable
  • Caveats list (jurisdiction legal boilerplate)
  • Detail table: one row per disposal, sorted by disposal date

For a typical user with a few dozen disposals this comes out to 2-4
pages. Heavy traders may get 20+ pages — we don't paginate aggressively.

CSV formats
-----------
  tax_report.csv    — generic, works with every accountant tool
  form_8949.csv     — IRS Form 8949 Part I / II column layout
                      (Description, Date Acquired, Date Sold, Proceeds,
                       Cost, Adjustment Code, Adjustment Amount, Gain)
"""
